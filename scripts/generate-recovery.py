"""Generate the embedded vehicle recovery archive from its readable SII files."""

from hashlib import sha256
from io import BytesIO
from pathlib import Path
from zipfile import ZIP_DEFLATED, ZipFile, ZipInfo


ROOT = Path(__file__).resolve().parent.parent
ASSET_ROOT = ROOT / "native" / "recovery" / "def" / "vehicle"
OUTPUT = ROOT / "native" / "heavymp_recovery_archive.h"
TRUCK_PATH = "def/vehicle/truck/fallback.sii"
TRAILER_PATH = "def/vehicle/trailer/fallback.sii"


def byte_array(name, value):
    rows = []
    for offset in range(0, len(value), 24):
        row = ",".join(f"0x{byte:02x}" for byte in value[offset : offset + 24])
        rows.append(row + ",")
    return f"constexpr unsigned char {name}[]={{\n" + "\n".join(rows) + "\n};\n"


def load_definitions():
    resources = {
        asset.relative_to(ASSET_ROOT.parent.parent).as_posix(): asset.read_bytes()
        for asset in sorted(ASSET_ROOT.glob("*/fallback.sii"))
    }
    truck = resources[TRUCK_PATH]
    trailer = resources[TRAILER_PATH]
    truck_paths = sorted(path for path in resources if path != TRAILER_PATH)

    if len(truck_paths) != 15:
        raise ValueError("Expected 15 truck recovery paths.")
    if not truck.startswith(b"SiiNunit") or b"vehicle : .fallback {" not in truck:
        raise ValueError("The truck fallback must define a complete vehicle.")
    if b"/engine/dc13_360.sii" not in truck:
        raise ValueError("The truck fallback must use the stock R360 engine.")
    if any(resources[path] != truck for path in truck_paths):
        raise ValueError("All truck recovery paths must contain the same definition.")
    if b"trailer : .fallback.trailer" not in trailer:
        raise ValueError("The trailer fallback must define a complete trailer.")
    if b"trailer_definition: trailer_def.scs.box.single_3.curtain" not in trailer:
        raise ValueError("The trailer fallback must use the stock curtainsider.")
    if trailer.count(b"{") != trailer.count(b"}"):
        raise ValueError("The trailer definition has unbalanced braces.")
    return resources, truck_paths, truck, trailer


def archive_bytes(resources):
    buffer = BytesIO()
    with ZipFile(buffer, "w", compression=ZIP_DEFLATED) as archive:
        for name, content in resources.items():
            entry = ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
            entry.compress_type = ZIP_DEFLATED
            archive.writestr(entry, content)
    return buffer.getvalue()


def main():
    resources, truck_paths, truck, trailer = load_definitions()
    blob = archive_bytes(resources)
    lines = [
        "// Generated by scripts/generate-recovery.py.\n",
        byte_array("nativeRecoveryZip", blob),
        byte_array("nativeRecoveryZipHash", sha256(blob).digest()),
        byte_array("nativeFallbackHash", sha256(truck).digest()),
        f"constexpr size_t nativeFallbackSize={len(truck)};\n",
        "constexpr const char* nativeFallbackPaths[]={\n",
    ]
    lines.extend(f'"/{name}",\n' for name in truck_paths)
    lines.extend([
        "};\n",
        byte_array("nativeTrailerFallbackHash", sha256(trailer).digest()),
        "struct NativeRecoveryEntry {const char* path; size_t size; const unsigned char* sha256;};\n",
        "constexpr NativeRecoveryEntry nativeRecoveryEntries[]={\n",
    ])
    lines.extend(
        f'{{"/{name}",nativeFallbackSize,nativeFallbackHash}},\n'
        for name in truck_paths
    )
    lines.extend([
        f'{{"/{TRAILER_PATH}",{len(trailer)},nativeTrailerFallbackHash}},\n',
        "};\n",
    ])
    OUTPUT.write_text("".join(lines), encoding="utf-8", newline="\n")
    print(f"Recovery archive generated: {len(blob)} bytes, {len(resources)} definitions.")


if __name__ == "__main__":
    main()

